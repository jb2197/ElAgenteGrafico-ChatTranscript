def boltzmann_weights(items):
    e = np.array([x['energy'] for x in items], dtype=float)
    emin = e.min()
    rel = e - emin
    w = np.exp(-beta * rel)
    w /= w.sum()
    rel_kcal = rel * HARTREE_TO_KCAL
    for item, rk, wi in zip(items, rel_kcal, w):
        item['dft_rel_kcal'] = float(rk)
        item['dft_weight'] = float(wi)
    return items

crest_gas = boltzmann_weights(crest_gas)
crest_solv = boltzmann_weights(crest_solv)

