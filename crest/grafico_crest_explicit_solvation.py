# Build broadened spectra on an energy grid
sigma_ev = 0.10
x_ev = np.linspace(7.5, 10.8, 3000)

def broadened_spectrum(items):
    y = np.zeros_like(x_ev)
    for item in items:
        w_conf = item['dft_weight']
        exc_ev = np.array(item['exc']) * HARTREE_TO_EV
        osc = np.array(item['osc'])
        for e, f in zip(exc_ev, osc):
            y += w_conf * f * np.exp(-0.5 * ((x_ev - e) / sigma_ev) ** 2)
    return y

spec_gas = broadened_spectrum(crest_gas)
spec_solv = broadened_spectrum(crest_solv)

# Peak positions
peak_gas_ev = x_ev[np.argmax(spec_gas)]
peak_solv_ev = x_ev[np.argmax(spec_solv)]
peak_gas_nm = 1239.841984 / peak_gas_ev
peak_solv_nm = 1239.841984 / peak_solv_ev

# First bright-state weighted statistics (lowest-energy state with f > 0.01 for each conformer)
def first_bright(items, threshold=0.01):
    vals = []
    weights = []
    for item in items:
        for exc, osc in zip(item['exc'], item['osc']):
            if osc > threshold:
                vals.append(exc * HARTREE_TO_EV)
                weights.append(item['dft_weight'])
                break
    vals = np.array(vals)
    weights = np.array(weights)
    mean = (vals * weights).sum() / weights.sum()
    return mean, 1239.841984 / mean

